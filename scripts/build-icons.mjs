// Collects every "set:name" icon the site uses into lib/icon-data.ts, so icons render as inline
// SVG at build time instead of being fetched from Iconify's API in the visitor's browser.
// Run after adding or renaming an icon:  node scripts/build-icons.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const require = createRequire(import.meta.url);
const SETS = { solar: "@iconify-json/solar", logos: "@iconify-json/logos", "simple-icons": "@iconify-json/simple-icons" };
const sets = Object.fromEntries(Object.entries(SETS).map(([k, pkg]) => [k, require(`${pkg}/icons.json`)]));

const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(tsx?|mjs)$/.test(name) && !p.endsWith("icon-data.ts")) files.push(p);
  }
};
["app", "components", "lib"].forEach(walk);

const names = new Set();
const re = new RegExp(`"((?:${Object.keys(SETS).join("|")}):[a-z0-9-]+)"`, "g");
for (const f of files) for (const m of readFileSync(f, "utf8").matchAll(re)) names.add(m[1]);

const out = {};
const missing = [];
for (const full of [...names].sort()) {
  const [prefix, name] = full.split(":");
  const set = sets[prefix];
  const resolved = set.icons[name] ?? set.icons[set.aliases?.[name]?.parent];
  if (!resolved) { missing.push(full); continue; }
  out[full] = { body: resolved.body, width: resolved.width ?? set.width ?? 24, height: resolved.height ?? set.height ?? 24 };
}
if (missing.length) { console.error("Unknown icons:", missing.join(", ")); process.exit(1); }

writeFileSync("lib/icon-data.ts",
  `// GENERATED by scripts/build-icons.mjs. Do not edit by hand.\n` +
  `export const ICONS: Record<string, { body: string; width: number; height: number }> = ${JSON.stringify(out, null, 2)};\n`);
console.log(`wrote lib/icon-data.ts: ${Object.keys(out).length} icons`);
